-- Automatic replacement of expiring keys, for providers the portal can mint in.

-- Where a provisioned key came from, kept on the key itself so a replacement can
-- be minted against the same provider resource later. Plain ids, no foreign key:
-- removing the integration must not take the keys it minted with it (rotation
-- simply stops being possible for them).
ALTER TABLE api_key ADD COLUMN integration_id BIGINT;
-- The provider-side handle the key hangs off: for Azure AD, the app
-- registration's object id. A replacement secret is added to this same client,
-- so the consumer's identity never changes - only the secret does.
ALTER TABLE api_key ADD COLUMN provider_resource_id VARCHAR(255);

-- The per-key override: NULL means "use the owner's setting for this provider",
-- FALSE/TRUE pin this one key off or on regardless of it.
ALTER TABLE api_key ADD COLUMN auto_rotate BOOLEAN;

-- Set on a replacement, pointing at the key it replaces. The unique index is the
-- idempotency guard: however many times the sweep looks at an expiring key, only
-- one replacement can ever be minted for it.
ALTER TABLE api_key ADD COLUMN rotated_from_key_id BIGINT;
CREATE UNIQUE INDEX idx_api_key_rotated_from ON api_key (rotated_from_key_id);

-- The owner's per-provider choice. Absent rows mean "off": replacing somebody's
-- credentials in a provider is strictly opt-in.
CREATE TABLE auto_rotation_preference (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    user_id    BIGINT      NOT NULL REFERENCES user_account (id) ON DELETE CASCADE,
    provider   VARCHAR(20) NOT NULL,
    enabled    BOOLEAN     NOT NULL,
    created_at TIMESTAMP   NOT NULL,
    updated_at TIMESTAMP   NOT NULL
);

CREATE UNIQUE INDEX idx_auto_rotation_pref_once ON auto_rotation_preference (user_id, provider);
